// Every word the shell draws (spec §8.7): the band, the board, the dialogs,
// the notifications and /gemflow all read one table. The key is the Chinese
// text with `{0}`-style holes; `en` and `ja` are its translations. A workflow's
// own titles and notes keep the language their author wrote. Pure and Node-free.

export type Lang = "zh" | "en" | "ja";
export const LANGS: readonly Lang[] = ["zh", "en", "ja"];

/** The words function: a key (the Chinese text) and its arguments, in the language chosen. */
export type T = (key: string, ...args: readonly (string | number)[]) => string;

/** `{0}`, `{1}`… replaced in order; a hole with no argument stays. */
export function fill(text: string, args: readonly (string | number)[]): string {
  return text.replace(/\{(\d+)\}/g, (hole, i: string) => (args[Number(i)] !== undefined ? String(args[Number(i)]) : hole));
}

/**
 * The language for a setting and a locale: `system` follows the locale
 * (`zh*` Chinese, `ja*` Japanese, anything else English); an explicit choice
 * is itself; nothing known is Chinese, the words' own language.
 */
export function langOf(setting: string | undefined, locale: string | undefined): Lang {
  if (setting === "zh" || setting === "en" || setting === "ja") return setting;
  const code = (locale ?? "").trim().toLowerCase().replace(/[_-].*$/, "").replace(/\..*$/, "");
  if (code === "") return "zh";
  if (code === "zh") return "zh";
  if (code === "ja") return "ja";
  return "en";
}

