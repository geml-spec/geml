/** The words in `lang`: a key with no translation falls back to its Chinese text. */
export function wordsFor(lang: Lang): T {
  if (lang === "zh") return (key, ...args) => fill(key, args);
  return (key, ...args) => {
    const entry = WORDS[key] ?? EMPTY;
    const text = entry[lang];
    return fill(text === "" ? key : text, args);
  };
}

